/** 根据上下文查找课标要点，带降级策略 */
export function lookupCurriculum(ctx: TeacherContext): string {
  const key = `${ctx.stage}-${ctx.subject}-${ctx.grade}`;
  const stageSubject = `${ctx.stage}-${ctx.subject}`;
  return (
    CURRICULUM[key] ??
    CURRICULUM[stageSubject] ??
    CURRICULUM[ctx.stage] ??
    "暂无内置课标数据，请基于通用教学规律组织内容，不要虚构政策文件。"
  );
}
